"""Dev-time helper: extract flattened glyph outlines from system TTFs into fontdata.py.

Not used at render time (the renderer is stdlib-only and imports fontdata.py).
Run: python3 tools/genfont.py
"""
import os
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen

N = "/usr/share/fonts/truetype/noto/"
FONTS = {
    "SB": N + "NotoSerif-Bold.ttf",
    "SI": N + "NotoSerif-Italic.ttf",
    "CR": N + "NotoSans-SemiCondensed.ttf",
    "CB": N + "NotoSans-CondensedBold.ttf",
}
CHARS = [chr(c) for c in range(32, 127)] + [chr(c) for c in (0x2013, 0x2014, 0xB7, 0x2019, 0x2018, 0x201C, 0x201D,
    0x2212, 0xD7, 0xA3, 0xE9, 0xE1, 0xF3, 0xFC, 0xF1, 0xED, 0x2026, 0xB0, 0x20AC, 0xBD, 0x2022, 0x2192)]


class FlatPen(BasePen):
    def __init__(self, gs):
        super().__init__(gs)
        self.contours = []
        self.cur = None

    def _moveTo(self, p):
        self.cur = [p]

    def _lineTo(self, p):
        self.cur.append(p)

    def _curveToOne(self, p1, p2, p3):
        p0 = self.cur[-1]
        for i in range(1, 5):
            t = i / 4
            u = 1 - t
            x = u**3 * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t**3 * p3[0]
            y = u**3 * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t**3 * p3[1]
            self.cur.append((x, y))

    def _qCurveToOne(self, p1, p2):
        p0 = self.cur[-1]
        for i in range(1, 5):
            t = i / 4
            u = 1 - t
            x = u * u * p0[0] + 2 * u * t * p1[0] + t * t * p2[0]
            y = u * u * p0[1] + 2 * u * t * p1[1] + t * t * p2[1]
            self.cur.append((x, y))

    def _closePath(self):
        if self.cur:
            self.contours.append(self.cur)
        self.cur = None

    def _endPath(self):
        self._closePath()


def main():
    out = ["# GENERATED by tools/genfont.py from Noto fonts (SIL OFL). Flattened glyph outlines.",
           "# Font units, y up. FONTS[name] = (upm, {char: (advance, [flat contours])})", "FONTS = {"]
    for name, path in FONTS.items():
        f = TTFont(path)
        gs = f.getGlyphSet()
        cmap = f.getBestCmap()
        upm = f["head"].unitsPerEm
        out.append("%r: (%d, {" % (name, upm))
        for ch in CHARS:
            gn = cmap.get(ord(ch))
            if gn is None:
                continue
            pen = FlatPen(gs)
            gs[gn].draw(pen)
            adv = gs[gn].width
            cs = []
            for c in pen.contours:
                flat = []
                last = None
                for x, y in c:
                    q = (int(round(x)), int(round(y)))
                    if q != last:
                        flat.extend(q)
                        last = q
                cs.append(tuple(flat))
            out.append("%r:(%d,%r)," % (ch, adv, cs))
        out.append("}),")
    out.append("}")
    dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "fontdata.py")
    with open(dest, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote", dest, os.path.getsize(dest))


main()
